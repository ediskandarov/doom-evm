// Independent authenticated profile artifacts; never ship an IWAD or Frame payload.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {resolve} from 'node:path';
const sha=b=>createHash('sha256').update(b).digest('hex');
const pins={schemaVersion:1,profile:'doom2',memoryProfile:3,initializationAPI:'initializeMenuWithMemoryProfile(bool,uint8)',compiler:'0.8.37',evmVersion:'cancun',artifacts:{},sources:{}};
await mkdir('web/doom2-assets',{recursive:true});
for(const [name,source] of [['Doom','Doom2'],['ResourceStore','ResourceStore']]){
 const artifact=JSON.parse(await readFile(`artifacts/local/doom2/production/out/${source}.sol/${source}.json`));
 const metadata=typeof artifact.metadata==='string'?JSON.parse(artifact.metadata):artifact.metadata;
 if(!metadata.compiler.version.startsWith(pins.compiler)||metadata.settings.evmVersion!=='cancun'||!metadata.settings.viaIR||metadata.settings.optimizer.runs!==200)throw Error('Compiler policy mismatch');
 for(const [path,identity] of Object.entries(metadata.sources)){
  const b=await readFile(path),h=execFileSync(resolve('.toolchain/bin/cast'),['keccak'],{input:'0x'+b.toString('hex'),encoding:'utf8',maxBuffer:1048576}).trim();
  if(h!==identity.keccak256)throw Error('Source mismatch '+path);pins.sources[path]=sha(b);
 }
 if(Object.keys(artifact.bytecode.linkReferences??{}).length)throw Error('Unlinked artifact');
 const payload=JSON.stringify({bytecode:artifact.bytecode.object,runtime:artifact.deployedBytecode.object,immutableReferences:artifact.deployedBytecode.immutableReferences,methods:artifact.methodIdentifiers})+'\n';
 await writeFile(`web/doom2-assets/${name}.json`,payload);pins.artifacts[name]={url:`/doom2-assets/${name}.json`,sha256:sha(payload),runtimeBytes:(artifact.deployedBytecode.object.length-2)/2};
}
const palette=JSON.parse(await readFile('test/fixtures/wad/palette.json'));
// Reuse the redistributable Freedoom palette, whose bytes share the accepted pin.
// Only profile identity metadata changes; no commercial WAD payload is packaged.
palette.resourceIdentity=JSON.parse(await readFile('artifacts/doom2/resource-pin.json')).resourceIdentity;
await writeFile('web/doom2-assets/palette.json',JSON.stringify(palette)+'\n');
await writeFile('web/doom2-assets/COPYING-Freedoom.txt',await readFile('test/fixtures/wad/COPYING.txt'));
await writeFile('web/doom2-pins.mjs','// Generated by tools/reference/doom2/package.mjs; no commercial payload.\nexport default '+JSON.stringify(pins,null,2)+';\n');
console.log(JSON.stringify({artifacts:pins.artifacts,sources:Object.keys(pins.sources).length}));
