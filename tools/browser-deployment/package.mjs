import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {resolve} from 'node:path';
const source=resolve(process.argv[2]??'.'), sha=b=>createHash('sha256').update(b).digest('hex');
const pins={schemaVersion:1,compiler:'0.8.37',evmVersion:'cancun',artifacts:{},sources:{}};
await mkdir('web/install-assets',{recursive:true});
for(const name of ['Doom','ResourceStore']){
 const artifact=JSON.parse(await readFile(`${source}/out/${name}.sol/${name}.json`));
 const metadata=typeof artifact.metadata==='string'?JSON.parse(artifact.metadata):artifact.metadata;
 if(!metadata.compiler.version.startsWith(pins.compiler)||metadata.settings.evmVersion!=='cancun'||!metadata.settings.viaIR||metadata.settings.optimizer.runs!==200)throw Error('Compiler policy mismatch');
 for(const [path,identity] of Object.entries(metadata.sources)){
  const bytes=await readFile(path),digest=execFileSync(resolve('.toolchain/bin/cast'),['keccak'],{input:'0x'+bytes.toString('hex'),encoding:'utf8',maxBuffer:1048576}).trim();
  if(digest!==identity.keccak256)throw Error('Source mismatch '+path);pins.sources[path]=sha(bytes);
 }
 if(Object.keys(artifact.bytecode.linkReferences??{}).length)throw Error('Unlinked artifact');
 const payload=JSON.stringify({bytecode:artifact.bytecode.object,runtime:artifact.deployedBytecode.object,immutableReferences:artifact.deployedBytecode.immutableReferences,methods:artifact.methodIdentifiers});
 await writeFile(`web/install-assets/${name}.json`,payload+'\n');pins.artifacts[name]={url:`/install-assets/${name}.json`,sha256:sha(payload+'\n')};
}
const wad=await readFile(`${source}/artifacts/local/freedoom/freedoom1.wad`),lock=JSON.parse(await readFile('tools/wad/freedoom.lock.json'));
if(sha(wad)!==lock.wadSha256)throw Error('Freedoom authentication failed');
await writeFile('web/install-assets/freedoom1.wad',wad);
await writeFile('web/install-assets/palette.json',await readFile('test/fixtures/wad/palette.json'));
await writeFile('web/install-assets/COPYING-Freedoom.txt',await readFile('test/fixtures/wad/COPYING.txt'));
await writeFile('web/install-pins.mjs','// Generated by tools/browser-deployment/package.mjs; authenticated release artifacts.\nexport default '+JSON.stringify(pins,null,2)+';\n');
console.log(JSON.stringify({artifacts:pins.artifacts,sources:Object.keys(pins.sources).length,freedoomSha256:sha(wad)},null,2));
